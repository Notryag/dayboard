function valueAtPath(tree: MessageTree, key: string): string | undefined {
  const value = key.split(".").reduce<MessageTree | undefined>((current, part) => {
    if (!current || typeof current === "string") return undefined;
    return current[part];
  }, tree);
  return typeof value === "string" ? value : undefined;
}

export function getMessage(
  locale: Locale,
  key: string,
  values?: MessageValues,
): string {
  const template = valueAtPath(messages[locale], key) ?? valueAtPath(messages["zh-CN"], key) ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
}
